"""Build scene.js for Part 2 from Part 1's scene plus part2.js.

python3 build.py
Part 2 starts on Part 1's last frame, so it reuses Part 1's code unchanged: everything in part1/scene.js up to
(not including) its camera section, then its post chain, then part2.js (Part 2's story, camera, renderAt, metaAt).
Part 1's own camera / setT / renderAt are left out.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(HERE, 'part1', 'scene.js')).read()
BANNER = '// ----------------------------------------------------------------'


def section_start(name):
    i = src.find(f'{BANNER} {name}')
    assert i >= 0, name
    return i


world = src[:section_start('camera')]
post = src[section_start('post'):section_start('one sub-frame')]
assert world.count("fetch('timeline.json')") == 1
world = world.replace("fetch('timeline.json')", "fetch('part1/timeline.json')")
part2 = open(os.path.join(HERE, 'part2.js')).read()
head = ('// GENERATED by build.py: Part 1 (part1/scene.js, unchanged) world/rig/rocks/bag/lamp/dust + post, then part2.js.\n'
        '// Edit part2.js, not this file.\n')
open(os.path.join(HERE, 'scene.js'), 'w').write(head + world + post + part2)
print('wrote scene.js', len(world), len(post), len(part2))
