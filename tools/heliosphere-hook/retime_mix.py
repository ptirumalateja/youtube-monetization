s = s.replace("asplit=4[w1a][w1b][w1c][w1d];", "asplit=6[w1a][w1b][w1c][w1d][w1e][w1f];\n[w1e]atrim=3.6,asetpts=N/SR/TB,volume=0.75,adelay=5250|5250[wsp];\n[w1f]atrim=3.6,asetpts=N/SR/TB,volume=0.6,adelay=11900|11900[wdv];", 1)
s = s.replace("[16]aformat", fl + "[16]aformat", 1)
