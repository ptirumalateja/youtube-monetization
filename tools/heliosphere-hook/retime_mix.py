# v20: re-cut mix.sh (written in v19 picture time) to the v20 reel time, using the inverse of scene.js srcT (RMAP knots, Fritsch-Carlson).
import re, sys
K = [[0, 0], [3.4, 3.4], [6.2, 5.05], [6.7, 6.4], [9.4, 10.2], [11.6, 13.0], [13.6, 15.0], [16.8, 17.0], [18.8, 19.0], [21.0, 21.8], [24.2, 24.3], [25, 25]]
x = [k[0] for k in K]; y = [k[1] for k in K]; n = len(K)
d = [(y[i+1]-y[i])/(x[i+1]-x[i]) for i in range(n-1)]
m = [d[0]] + [2/(1/d[i-1]+1/d[i]) for i in range(1, n-1)] + [d[-1]]
def src(tn):
    tn = min(max(tn, 0), x[-1]); i = 0
    while i < n-2 and tn > x[i+1]: i += 1
    h = x[i+1]-x[i]; s = (tn-x[i])/h; s2 = s*s; s3 = s2*s
    return (2*s3-3*s2+1)*y[i]+(s3-2*s2+s)*h*m[i]+(-2*s3+3*s2)*y[i+1]+(s3-s2)*h*m[i+1]
def inv(to):
    lo, hi = 0.0, 25.0
    for _ in range(60):
        mid = (lo+hi)/2
        if src(mid) < to: lo = mid
        else: hi = mid
    return lo
s = open('mix.sh').read()
OVR = {'rhit2': 14250, 'rise3': 22500, 'sub2': 6200, 'swish3': 19150, 'swish4': 21150, 'accent2': 21650, 'rehook': 11750, 'accent': 11750, 'boom3': 16800,
       'zap2': 16800, 'spark4': 16820, 'plasma3': 16900, 'suck': 15400, 'dive2': 24050, 'warp2': 24150, 'suck2': 24200}
def fix_delay(mo):
    ms = int(mo.group(1)); label = mo.group(3)
    v = OVR.get(label, round(inv(ms/1000)*1000))
    return f"adelay={v}|{v}{mo.group(2)}[{label}]"
s = re.sub(r"adelay=(\d+)\|\d+([^\[]*)\[(\w+)\]", fix_delay, s)
def fix_between(mo):
    a, b = float(mo.group(1)), float(mo.group(2))
    return f"between(t,{inv(a):.2f},{inv(b):.2f})"
s = re.sub(r"between\(t,([\d.]+),([\d.]+)\)", fix_between, s)
# the crossing gap and the gap before WOULD YOU GO? sit right before their hits in reel time
s = re.sub(r"if\(between\(t,[\d.]+,[\d.]+\),0\.12,if\(between\(t,[\d.]+,[\d.]+\),0\.12,1\)\)", "if(between(t,16.68,16.8),0.12,if(between(t,21.52,21.65),0.12,1))", s)
# fill the two quiet holes: 12.5-13.6 (the dive onto Voyager) and 18.4-21.1 (the pull-back under the light-day line)
s = s.replace("-i $L/869757", "-i $L/115555__vartioh__synth_jet.wav -i $L/238375__stewdio2003__cp_subby_whoosh.aiff -i $L/869757")
s = re.sub(r"\[(1[4-9])\]", lambda mo: f"[{int(mo.group(1))+2}]", s)   # inputs 14,15 shift to 16,17
F = [(1.8, 1.8, 0.6, 12350), (1.8, 2.9, 0.5, 18300), (1.8, 1.5, 0.55, 5300), (2.0, 1.5, 0.5, 8250), (1.8, 2.4, 0.4, 20900)]
